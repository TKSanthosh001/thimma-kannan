/**
 * Gets the active or next upcoming Tamil festival based on current date
 */
export const getActiveOrUpcomingFestival = () => {
  const todayStr = new Date().toISOString().split('T')[0];
  
  // 1. Check if today matches any festival
  const todayFest = tamilFestivals.find(f => f.date === todayStr);
  if (todayFest) {
    return { festival: todayFest, isToday: true };
  }

  // 2. Find next upcoming festival
  const upcomingFestivals = tamilFestivals.filter(f => f.date > todayStr);
  if (upcomingFestivals.length > 0) {
    // Sort ascending by date
    upcomingFestivals.sort((a, b) => a.date.localeCompare(b.date));
    return { festival: upcomingFestivals[0], isToday: false };
  }

  // Fallback to first festival if end of year
  return { festival: tamilFestivals[0], isToday: false };
};
